"""
The two pre-recorded lines California says when she stops listening for a
follow-up answer, loaded once at startup.

    timeout  a window in a chain went unanswered
    cap      conversation.max_follow_ups follow-ups in a row

They are generated by generate_stop_lines.py into
sounds/stop_lines/<provider>_<voice>/, in the voice config.yaml selects, and
are not committed (same as every other generated clip). They are never
synthesized at runtime: a missing clip is a warning here and silence later,
and the conversation still ends normally.
"""

import json
import logging
import os

import numpy as np

logger = logging.getLogger(__name__)

STOP_LINE_NAMES = ("timeout", "cap")

_REPO_ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))


def load_stop_lines(directory: str) -> dict[str, tuple[np.ndarray, int, str]]:
    """
    Read `<directory>/{timeout,cap}.wav` and their text from manifest.json.

    Returns {name: (audio, sample_rate, text)} for every clip that loaded; a
    missing or unreadable one is skipped with a warning. Never raises.
    """
    if not directory:
        logger.warning("No sounds.stop_lines_dir configured; run generate_stop_lines.py")
        return {}
    if not os.path.isabs(directory):
        directory = os.path.join(_REPO_ROOT, directory)
    directory = os.path.normpath(directory)

    texts: dict = {}
    try:
        with open(os.path.join(directory, "manifest.json"), encoding="utf-8") as fh:
            loaded = json.load(fh)
        if isinstance(loaded, dict):
            texts = loaded
    except Exception:
        texts = {}

    try:
        import soundfile as sf
    except Exception:
        logger.warning("soundfile is unavailable; stop lines will not play")
        return {}

    lines: dict[str, tuple[np.ndarray, int, str]] = {}
    for name in STOP_LINE_NAMES:
        path = os.path.join(directory, f"{name}.wav")
        try:
            audio, sample_rate = sf.read(path, dtype="float32")
        except Exception:
            logger.warning(
                "Stop line %r missing at %s; run generate_stop_lines.py", name, path
            )
            continue
        text = texts.get(name, "")
        lines[name] = (audio, int(sample_rate), text if isinstance(text, str) else "")
    return lines
